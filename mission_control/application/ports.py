"""Structural interfaces for application dependencies."""

from typing import Protocol
from mission_control.domain import ReportInput, ReportRecord


class ReportStore(Protocol):
    def add(self, report: ReportRecord) -> None: ...
    def list_reports(self) -> list[ReportRecord]: ...
    def get(self, report_id: str) -> ReportRecord: ...
    def approve(self, report_id: str, approver_name: str) -> ReportRecord: ...


class ReportBuilder(Protocol):
    async def build(self, report_input: ReportInput) -> ReportRecord: ...
